// Bundles the action to one file, dist/index.cjs, which action.yml runs on node24 (github-action plan §3.2). The bundle
// is committed (an action runs from the ref it's used at); `--check` rebuilds in memory and fails if the committed one
// is stale, like openapi:check. Not minified, so stack traces in a job log stay readable.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { build } from 'esbuild'

const root = join(import.meta.dirname, '..')
const out = join(root, 'dist/index.cjs')
const check = process.argv.includes('--check')

const result = await build({
  entryPoints: [join(root, 'src/entry.ts')],
  bundle: true,
  platform: 'node',
  target: 'node24',
  format: 'cjs',
  write: false,
  legalComments: 'none',
  logLevel: 'warning',
  banner: { js: '// Generated by packages/action/scripts/build.ts. Do not edit; run npm run action:build.' },
})
const code = result.outputFiles[0]?.text ?? ''

if (check) {
  let committed: string
  try {
    committed = readFileSync(out, 'utf8')
  } catch {
    committed = ''
  }
  if (committed !== code) {
    console.error('packages/action/dist/index.cjs is out of date. Run: npm run action:build')
    process.exit(1)
  }
  console.log('packages/action/dist/index.cjs is up to date.')
} else {
  writeFileSync(out, code)
  console.log(
    JSON.stringify({ step: 'action-bundle', file: 'packages/action/dist/index.cjs', bytes: code.length }),
  )
}
