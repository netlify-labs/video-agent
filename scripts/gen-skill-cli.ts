// Writes skills/netlify-video/references/cli.md from the CLI's catalog (cli-and-sdk plan §8; bead va-p1th.7.5), so
// the skill never lists a command, flag or exit code the CLI doesn't have. Only ready commands are listed; the
// sections for `local` and `brief` appear once those commands are ready. {{SITE_URL}} is filled in when the skill is
// packaged.
//
//   npx tsx scripts/gen-skill-cli.ts          # writes the file
//   npx tsx scripts/gen-skill-cli.ts --check  # exits 1 if it's stale (test/skill-cli.test.ts runs the same check)
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { format, resolveConfig } from 'prettier'
import { COMMANDS, GLOBAL_FLAGS, type CommandSpec } from '../packages/cli/src/catalog.js'
import { EXIT, EXIT_MEANINGS } from '../packages/cli/src/exit.js'

export const CLI_MD = join(import.meta.dirname, '../skills/netlify-video/references/cli.md')

const usage = (c: CommandSpec) =>
  [
    'video-agent',
    c.name,
    ...c.args.map((a) =>
      a.required ? `<${a.name}${a.variadic ? '…' : ''}>` : `[${a.name}${a.variadic ? '…' : ''}]`,
    ),
  ].join(' ')

const flagLine = (name: string, f: { type: string; description: string; multiple?: boolean }) =>
  `\`--${name}${f.type === 'boolean' ? '' : ` <${f.type === 'number' ? 'n' : 'value'}>`}\`${f.multiple ? ' (repeatable)' : ''}: ${f.description}`

function command(c: CommandSpec): string {
  const lines = [
    `### ${c.name}`,
    '',
    `${c.summary}${c.feature ? ` Needs the server feature "${c.feature}" (see whoami).` : ''}`,
    '',
  ]
  lines.push('```sh', usage(c), ...c.examples, '```')
  const flags = Object.entries(c.flags)
  if (flags.length) lines.push('', ...flags.map(([n, f]) => `- ${flagLine(n, f)}`))
  return lines.join('\n')
}

/** The file as written: rendered, then formatted the way the repo's Prettier formats Markdown. */
export async function renderCliMd(): Promise<string> {
  const ready = COMMANDS.filter((c) => c.ready && c.name !== 'help' && c.name !== 'version')
  const has = (name: string) => ready.some((c) => c.name === name)
  const out: string[] = [
    '# The video-agent CLI',
    '',
    '<!-- Generated by scripts/gen-skill-cli.ts from packages/cli/src/catalog.ts. Do not edit by hand. -->',
    '',
    'When you have a shell, the CLI is simpler than the MCP polling loop: one command makes a video, waits for it and',
    'downloads it, and `--json` gives you one object to read. The MCP recipes in [recipes.md](recipes.md) still apply;',
    'the CLI is another way to run the same steps.',
    '',
    '## Set up',
    '',
    '```sh',
    'npx netlify-video-agent --version          # or: npm i -g netlify-video-agent, then video-agent …',
    'video-agent login --url {{SITE_URL}}        # approve this terminal in the browser; the key is saved for you',
    'printf %s "$VIDEO_AGENT_API_KEY" | video-agent login --url {{SITE_URL}} --key - --no-save   # CI: a key, not saved',
    'video-agent whoami',
    '```',
    '',
    'Instead of `login`, set `VIDEO_AGENT_URL={{SITE_URL}}` and `VIDEO_AGENT_KEY=nva_…` in the environment. Flags win',
    'over the environment, which wins over the saved config. Never put a key on the command line or in a prompt.',
    '',
    '## Making a video',
    '',
    '```sh',
    'video-agent create "A 20-second launch video for our webhooks feature" --aspect 16:9 --wait --out ./webhooks --json',
    '```',
    '',
    '`--wait` follows the run (3 to 8 minutes) with progress on stderr; `--out` downloads the MP4, poster and captions.',
    'Upload screenshots or logos first with `video-agent media upload <file> --caption "…"` and pass the ids with',
    '`--media`, or pass the file to `--media` directly and it is uploaded first. A revision changes only what you say:',
    '`video-agent revise <video> "Make the end card orange" --wait`.',
    '',
  ]
  if (has('brief pr'))
    out.push(
      'From a pull request: `video-agent brief pr <url> | video-agent create --prompt-file - --wait`.',
      '',
    )
  if (has('local'))
    out.push(
      'No deployment? `video-agent local "<prompt>"` makes the video on this machine with your own coding agent.',
      '',
    )
  out.push(
    '## Output and errors',
    '',
    'With `--json`, stdout is exactly one JSON object: what the command made or read (a video has `id`,',
    '`latestVersion` and `versions[]` with `status`), or `{ "error": { "code", "message", "requestId" } }`. Progress',
    'and prompts go to stderr. `<video>` is an id (`vid_…`), its web address or a share link. Add `--verbose` for',
    'one JSON line per request on stderr, with request ids.',
    '',
    '| Exit | Meaning |',
    '| --- | --- |',
    ...Object.entries(EXIT).map(([k, v]) => `| ${v} | ${EXIT_MEANINGS[k as keyof typeof EXIT]} |`),
    '',
    '## Flags every command takes',
    '',
    ...Object.entries(GLOBAL_FLAGS).map(([n, f]) => `- ${flagLine(n, f)}`),
    '',
    '## Commands',
    '',
    ready.map(command).join('\n\n'),
    '',
  )
  return format(out.join('\n'), { ...(await resolveConfig(CLI_MD)), filepath: CLI_MD })
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const want = await renderCliMd()
  if (process.argv.includes('--check')) {
    const have = readFileSync(CLI_MD, 'utf8')
    if (have !== want) {
      console.error(`${CLI_MD} is stale. Run: npx tsx scripts/gen-skill-cli.ts`)
      process.exit(1)
    }
    console.log(`${CLI_MD} is up to date.`)
  } else {
    writeFileSync(CLI_MD, want)
    console.log(`wrote ${CLI_MD}`)
  }
}
