// Bundles the MCP App video card (ui/src/mcp-app/video-card.ts) into one HTML page, inlined as a string in
// src/generated/video-card.ts. MCP clients load the page from resources/read into a sandboxed iframe, so it has no
// files of its own: the script and styles are inline, and only the site's own file links load from outside.
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { build } from 'esbuild'

