export async function buildMcpApp(repoRoot: string) {
  const out = await build({
    entryPoints: [join(repoRoot, 'ui/src/mcp-app/video-card.ts')],
    bundle: true,
    format: 'iife',
    minify: true,
    target: 'es2022',
    write: false,
    legalComments: 'none',
  })
  // A closing script tag inside the bundle would end the inline script early.
  const js = (out.outputFiles[0]?.text ?? '').replace(/<\/script/gi, '<\\/script')
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Video card</title><style>${CSS.trim()}</style></head><body><main id="card" aria-live="polite"><p class="meta">Loading the video…</p></main><script>${js}</script></body></html>`
  writeFileSync(
    join(repoRoot, 'src/generated/video-card.ts'),
    `// Generated by scripts/build.ts from ui/src/mcp-app/video-card.ts (scripts/lib/mcp-app.ts). Do not edit.\nexport const videoCardHtml: string = ${JSON.stringify(html)}\n`,
  )
  return { bytes: html.length }
}
