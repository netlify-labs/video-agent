// The looks build step (plan 2026-11-04-looks §4.3, §4.8). scripts/build.ts calls it twice:
//   buildLooks(…, { writeArchives: true }) early, for every build (video-run previews too, since the API function
//     carries looks-build/*.tar.gz through included_files): checks each look, packs looks-build/<id>.tar.gz and
//     writes src/generated/looks.ts;
//   copyLookPreviews(…) after `vite build ui` (which empties ui/dist): the picker's clips and posters, content-hashed
//     under ui/dist/assets/looks/ so /assets/*'s immutable cache header applies.
// A look that fails look:check --static fails the build: a broken look never deploys.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { lookIds } from '../look-check.js'
import { checkLookStatic } from './look-static.js'
import { sha256Hex as sha256 } from '../../src/lib/crypto.js'
import {
  buildLookArchive,
  LookJsonSchema,
  readLookRunFiles,
  type LookCatalogEntry,
} from '../../src/lib/looks.js'

export class LookBuildError extends Error {
  constructor(readonly problems: string[]) {
    super(`Looks failed look:check --static:\n${problems.join('\n')}`)
  }
}

const PREVIEWS = [
  ['mp4', 'preview.mp4'],
  ['poster', 'poster.webp'],
] as const

/** Where a look's preview file is served: /assets/looks/<id>.<first 12 of its sha256>.<ext>. */
function previewPath(dir: string, id: string, file: string): string | null {
  const path = join(dir, file)
  if (!existsSync(path)) return null
  const ext = file.slice(file.lastIndexOf('.'))
  return `/assets/looks/${id}.${sha256(readFileSync(path)).slice(0, 12)}${ext}`
}

export interface BuildLooksOptions {
  repoRoot: string
  hyperframesVersion: string
  /** Write looks-build/<id>.tar.gz (the build); looks:gen only needs the catalog. */
  writeArchives: boolean
}

/** Every look under looks/ (not _template), checked and catalogued, `clean` first then by id. */
export function buildLooks(opts: BuildLooksOptions): LookCatalogEntry[] {
  const looksDir = join(opts.repoRoot, 'looks')
  const ids = lookIds(looksDir).filter((id) => id !== '_template')
  const problems = ids.flatMap((id) =>
    checkLookStatic(join(looksDir, id), { hyperframesVersion: opts.hyperframesVersion }).map(
      (p) => `look:${id}: ${p}`,
    ),
  )
  if (problems.length) throw new LookBuildError(problems)

  const entries: LookCatalogEntry[] = []
  for (const id of ids) {
    const dir = join(looksDir, id)
    const look = LookJsonSchema.parse(JSON.parse(readFileSync(join(dir, 'look.json'), 'utf8')))
    const archive = buildLookArchive(readLookRunFiles(dir))
    if (opts.writeArchives) {
      mkdirSync(join(opts.repoRoot, 'looks-build'), { recursive: true })
      writeFileSync(join(opts.repoRoot, 'looks-build', `${id}.tar.gz`), archive.bytes)
    }
    entries.push({
      id,
      name: look.name,
      description: look.description,
      tags: look.tags,
      bestFor: look.bestFor,
      aspects: look.aspects,
      engines: look.engines,
      recording: look.recording ?? null,
      musicMood: look.sound?.musicMood ?? null,
      hash: archive.hash,
      sha256: archive.sha256,
      bytes: archive.bytesLength,
      source: 'builtin',
      preview: { mp4: previewPath(dir, id, 'preview.mp4'), poster: previewPath(dir, id, 'poster.webp') },
    })
  }
  return entries.sort((a, b) => (a.id === 'clean' ? -1 : b.id === 'clean' ? 1 : a.id < b.id ? -1 : 1))
}

/** The source of src/generated/looks.ts. */
export function looksModule(entries: LookCatalogEntry[]): string {
  return `// Generated by scripts/build.ts (or npm run looks:gen) from looks/. Do not edit.
import type { LookCatalogEntry } from '../lib/looks.js'

export const looksCatalog: LookCatalogEntry[] = ${JSON.stringify(entries, null, 2)}
`
}

export function writeLooksModule(repoRoot: string, entries: LookCatalogEntry[]): void {
  mkdirSync(join(repoRoot, 'src', 'generated'), { recursive: true })
  writeFileSync(join(repoRoot, 'src', 'generated', 'looks.ts'), looksModule(entries))
}

/** Copies each look's preview and poster to their catalog paths under `distDir`. Returns how many it copied. */
export function copyLookPreviews(repoRoot: string, entries: LookCatalogEntry[], distDir: string): number {
  let copied = 0
  for (const e of entries)
    for (const [key, file] of PREVIEWS) {
      const to = e.preview[key]
      if (!to) continue
      mkdirSync(join(distDir, 'assets', 'looks'), { recursive: true })
      copyFileSync(join(repoRoot, 'looks', e.id, file), join(distDir, to))
      copied++
    }
  return copied
}
