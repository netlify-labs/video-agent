// The build-info module scripts/build.ts writes (cli-and-sdk plan §5.1): the deployed commit and, for our template
// releases, the release tag. Build-time variables like COMMIT_REF aren't reliably in the function's env, so the
// build bakes them in.
import { execFileSync } from 'node:child_process'

export interface BuildInfo {
  commit: string | null
  release: string | null
}

/** The release tag on HEAD when it's one of ours (v1.2.3), else null. */
export function releaseTag(cwd: string): string | null {
  try {
    const tag = execFileSync('git', ['describe', '--tags', '--exact-match', 'HEAD'], {
      cwd,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
    return /^v\d/.test(tag) ? tag : null
  } catch {
    return null
  }
}

export function buildInfoOf(env: NodeJS.ProcessEnv, release: string | null): BuildInfo {
  return { commit: env.COMMIT_REF || null, release }
}

export function buildInfoModule(info: BuildInfo): string {
  return `// Generated by scripts/build.ts: which build this deployment runs. Do not edit.\nexport const buildInfo: { commit: string | null; release: string | null } = ${JSON.stringify(info, null, 2)}\n`
}
