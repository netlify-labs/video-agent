// Writes packages/sdk/api.md: the SDK's public declarations (cli-and-sdk plan §4.5 API report), so every added,
// renamed or removed name shows in review. The declarations come from the TypeScript compiler, in memory, for every
// source file except the generated schema (its types follow openapi.json, which has its own check). --check fails
// when the committed report is stale.
import { join, relative } from 'node:path'
import ts from 'typescript'
import { repoRoot, writeOrCheck } from './lib/run-tools.js'

const pkg = join(repoRoot, 'packages/sdk')

export function apiReport(): string {
  const configPath = join(pkg, 'tsconfig.build.json')
  const parsed = ts.parseJsonConfigFileContent(
    ts.readConfigFile(configPath, (p) => ts.sys.readFile(p)).config,
    ts.sys,
    pkg,
  )
  const program = ts.createProgram(parsed.fileNames, {
    ...parsed.options,
    noEmit: false,
    declaration: true,
    emitDeclarationOnly: true,
  })
  const out = new Map<string, string>()
  program.emit(undefined, (file, text) => {
    const rel = relative(join(pkg, 'dist'), file)
    if (!rel.startsWith('generated/schema')) out.set(rel, text)
  })
  const sections = [...out.keys()].sort().map((f) => `## ${f}\n\n\`\`\`ts\n${out.get(f)?.trim()}\n\`\`\`\n`)
  return `# netlify-video-agent-sdk API report\n\nGenerated by \`npx tsx scripts/sdk-api-report.ts\` from packages/sdk/src. Do not edit.\n\n${sections.join('\n')}`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeOrCheck(join(pkg, 'api.md'), apiReport(), {
    check: process.argv.includes('--check'),
    label: 'packages/sdk/api.md',
    hint: 'Run `npx tsx scripts/sdk-api-report.ts` and commit it.',
  })
}
