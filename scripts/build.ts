// Build: generate the context module, then build the web app. Agent-run preview builds skip the UI
// (the run never uses its preview; outputs go to Blobs and callbacks go to production).
import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { repoRoot } from './lib/run-tools.js'

const log = (step: string, f: Record<string, unknown> = {}) => console.log(JSON.stringify({ step, ...f }))

const brand = JSON.parse(readFileSync(join(repoRoot, 'context/brand.json'), 'utf8')) as {
  name?: string
  primaryColor?: string
  logo?: string | null
  default?: boolean
}
const brandMd = readFileSync(join(repoRoot, 'context/BRAND.md'), 'utf8')
const isDefault = brand.default === true || brandMd.includes('video-agent:default')
let logo: string | null = null
if (brand.logo) {
  const svg = readFileSync(join(repoRoot, 'context', brand.logo), 'utf8')
  logo = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`
}
const meta = { isDefault, name: brand.name ?? 'Video Agent', primaryColor: brand.primaryColor ?? '#14b8a6', logo }
mkdirSync(join(repoRoot, 'src/generated'), { recursive: true })
writeFileSync(
  join(repoRoot, 'src/generated/context.ts'),
  `// Generated by scripts/build.ts from context/brand.json. Do not edit.\nexport const contextMeta = ${JSON.stringify(meta, null, 2)} as {\n  isDefault: boolean\n  name: string\n  primaryColor: string\n  logo: string | null\n}\n`,
)
log('context', { isDefault, name: meta.name })

const agentRun = Object.keys(process.env).some((k) => k.startsWith('NETLIFY_AGENT_RUNNER_')) || process.env.AI_AGENT !== undefined
log('build-env', { context: process.env.CONTEXT ?? null, agentRun, agentVars: Object.keys(process.env).filter((k) => /AGENT/.test(k)).sort() })
if (agentRun && process.env.FORCE_UI_BUILD !== 'true') {
  mkdirSync(join(repoRoot, 'ui/dist'), { recursive: true })
  writeFileSync(join(repoRoot, 'ui/dist/index.html'), '<!doctype html><title>Agent run preview</title><p>Agent run preview: the web app is not built here.</p>\n')
  log('ui', { skipped: true })
} else {
  execFileSync('npx', ['vite', 'build', 'ui'], { stdio: 'inherit', cwd: repoRoot })
  log('ui', { skipped: false })
}
